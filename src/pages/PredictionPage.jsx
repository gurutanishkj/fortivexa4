import React, { useState, useEffect } from 'react';
import { 
  Compass, 
  MapPin, 
  Clock, 
  TrendingUp, 
  ShieldAlert, 
  CheckCircle2, 
  Cpu, 
  ArrowRight, 
  Layers, 
  ShieldCheck, 
  FileText, 
  HelpCircle 
} from 'lucide-react';
import { runPrediction, fetchComplaintById } from '../services/api';

