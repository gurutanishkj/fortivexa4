  const [predictionResult, setPredictionResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [caseMeta, setCaseMeta] = useState(null);

  useEffect(() => {
    if (activeCaseId && activeCaseId !== caseId) {
      setCaseId(activeCaseId);
    }
  }, [activeCaseId]);

  function executePrediction(targetId) {
    setLoading(true);
    fetchComplaintById(targetId)
      .then(c => setCaseMeta(c))
      .catch(console.error);

    runPrediction(targetId)
      .then(res => {
        setPredictionResult(res);
        setLoading(false);
      })
      .catch(err => {
        console.error(err);
        setLoading(false);
      });
  }

  useEffect(() => {
    executePrediction(caseId);
  }, [caseId]);

  const topCandidate = predictionResult?.top_ranked_candidate;
  const allCandidates = predictionResult?.all_ranked_candidates || [];
  const muleChain = predictionResult?.analyzed_mule_chain || {};
  const metadata = predictionResult?.model_metadata || {};

